CREATE TABLE IF NOT EXISTS `media_assets` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Media asset ID',
  `kind` VARCHAR(10) NOT NULL COMMENT 'MEDIA kind: AUDIO or COVER',
  `bucket` VARCHAR(100) NOT NULL COMMENT 'Object storage bucket',
  `object_key` VARCHAR(500) NOT NULL COMMENT 'Object storage key',
  `content_type` VARCHAR(100) NOT NULL COMMENT 'MIME content type',
  `original_filename` VARCHAR(255) NOT NULL COMMENT 'Original upload filename',
  `size_bytes` BIGINT NOT NULL COMMENT 'Object size in bytes',
  `sha256` CHAR(64) NOT NULL COMMENT 'SHA-256 hex digest',
  `created_at` DATETIME(6) NOT NULL COMMENT 'Created timestamp in UTC',
  `created_by` INT NOT NULL COMMENT 'Creating user ID',
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_media_assets_bucket_object_key` (`bucket`, `object_key`),
  KEY `ix_media_assets_sha256` (`sha256`),
  CONSTRAINT `fk_media_assets_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_media_assets_kind` CHECK (`kind` IN ('AUDIO','COVER')),
  CONSTRAINT `ck_media_assets_size_bytes` CHECK (`size_bytes` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `tracks` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Track ID',
  `title` VARCHAR(255) NOT NULL COMMENT 'Track title',
  `artist_name` VARCHAR(255) NOT NULL COMMENT 'Primary artist name',
  `album_name` VARCHAR(255) DEFAULT NULL COMMENT 'Album name',
  `duration_ms` BIGINT DEFAULT NULL COMMENT 'Duration in milliseconds',
  `track_number` INT DEFAULT NULL COMMENT 'Track number',
  `disc_number` INT DEFAULT NULL COMMENT 'Disc number',
  `audio_asset_id` BIGINT NOT NULL COMMENT 'Primary audio media asset ID',
  `cover_asset_id` BIGINT DEFAULT NULL COMMENT 'Optional cover media asset ID',
  `id3_metadata` JSON DEFAULT NULL COMMENT 'Raw extracted ID3 metadata',
  `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT 'Track lifecycle status',
  `created_at` DATETIME(6) NOT NULL COMMENT 'Created timestamp in UTC',
  `updated_at` DATETIME(6) NOT NULL COMMENT 'Updated timestamp in UTC',
  `created_by` INT NOT NULL COMMENT 'Creating user ID',
  `updated_by` INT NOT NULL COMMENT 'Last updating user ID',
  PRIMARY KEY (`id`),
  KEY `ix_tracks_status` (`status`),
  KEY `ix_tracks_title` (`title`),
  KEY `ix_tracks_artist_name` (`artist_name`),
  KEY `ix_tracks_album_name` (`album_name`),
  CONSTRAINT `fk_tracks_audio_asset` FOREIGN KEY (`audio_asset_id`) REFERENCES `media_assets` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_tracks_cover_asset` FOREIGN KEY (`cover_asset_id`) REFERENCES `media_assets` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_tracks_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_tracks_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_tracks_status` CHECK (`status` IN ('DRAFT','PUBLISHED','ARCHIVED')),
  CONSTRAINT `ck_tracks_duration_ms` CHECK (`duration_ms` IS NULL OR `duration_ms` >= 0),
  CONSTRAINT `ck_tracks_track_number` CHECK (`track_number` IS NULL OR `track_number` > 0),
  CONSTRAINT `ck_tracks_disc_number` CHECK (`disc_number` IS NULL OR `disc_number` > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `media_imports` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Media import ID',
  `upload_id` CHAR(36) NOT NULL COMMENT 'Client-generated idempotency key',
  `status` VARCHAR(20) NOT NULL COMMENT 'Import lifecycle status',
  `original_filename` VARCHAR(255) NOT NULL COMMENT 'Original upload filename',
  `content_type` VARCHAR(100) NOT NULL COMMENT 'Declared MIME content type',
  `size_bytes` BIGINT DEFAULT NULL COMMENT 'Received object size in bytes',
  `sha256` CHAR(64) DEFAULT NULL COMMENT 'SHA-256 hex digest',
  `track_id` BIGINT DEFAULT NULL COMMENT 'Created track ID',
  `failure_code` VARCHAR(100) DEFAULT NULL COMMENT 'Stable failure code',
  `failure_reason` VARCHAR(1000) DEFAULT NULL COMMENT 'Non-sensitive failure detail',
  `created_at` DATETIME(6) NOT NULL COMMENT 'Created timestamp in UTC',
  `updated_at` DATETIME(6) NOT NULL COMMENT 'Updated timestamp in UTC',
  `created_by` INT NOT NULL COMMENT 'Creating user ID',
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_media_imports_upload_id` (`upload_id`),
  KEY `ix_media_imports_status_created_at` (`status`, `created_at`),
  CONSTRAINT `fk_media_imports_track` FOREIGN KEY (`track_id`) REFERENCES `tracks` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_media_imports_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_media_imports_status` CHECK (`status` IN ('UPLOADING','VALIDATING','EXTRACTING','READY','FAILED')),
  CONSTRAINT `ck_media_imports_size_bytes` CHECK (`size_bytes` IS NULL OR `size_bytes` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
